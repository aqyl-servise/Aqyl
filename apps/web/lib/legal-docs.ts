/**
 * Тексты публичных документов.
 *
 * Сюда вставляется готовый текст — по одному документу на ключ. Пока текст
 * пустой, страница показывает состояние «документ готовится», а не выдуманное
 * содержимое: публиковать сгенерированный юридический текст нельзя.
 *
 * Формат: обычный текст. Пустая строка разделяет абзацы; строка, начинающаяся
 * с «## », становится подзаголовком.
 *
 * Статус по документу «Что нужно сделать до публикации»:
 *   privacy — написана, требует правки под решения части 0
 *   consent — написано
 *   terms   — не начато, требуется для подключения Kaspi
 */
export interface LegalDoc {
  slug: string;
  title: string;
  /** Дата последней редакции, напр. «08.08.2026». Пустая — не показываем. */
  updatedAt: string;
  /** Полный текст документа. Пустой — страница покажет «готовится». */
  body: string;
}

