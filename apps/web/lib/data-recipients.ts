/**
 * Перечень получателей персональных данных.
 *
 * Вынесен на отдельную страницу намеренно — это конструкция «на вырост».
 * Сменили поставщика моделей или добавили эквайринг — обновили одну строку
 * здесь. Политику при этом переписывать и заново собирать согласия не нужно,
 * потому что политика ссылается на страницу, а не перечисляет получателей
 * внутри себя.
 *
 * ПРАВИЛО: строка появляется здесь только тогда, когда передача действительно
 * происходит. Перечислить «на всякий случай» тех, кому мы данные не передаём,
 * — это ввести человека в заблуждение ровно так же, как умолчать о реальном
 * получателе.
 */
export interface DataRecipient {
  /** Наименование организации. */
  name: string;
  /** Страна размещения — ключевой признак для трансграничной передачи. */
  country: string;
  /** Зачем передаём. */
  purpose: string;
  /** Что именно уходит. */
  data: string;
}

