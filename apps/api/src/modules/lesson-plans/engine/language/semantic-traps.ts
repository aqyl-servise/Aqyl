/**
 * Уровень 3 языкового шлюза (ТЗ 1.6, п. 3.2): пары слов, различающиеся одной
 * буквой, но радикально по смыслу. Срабатывание — только когда ошибочное
 * слово стоит в контексте, где ожидается правильное (маркеры рядом), иначе
 * слово может быть легитимным («сынық» в физике — сломанный).
 *
 * Пополняется по мере находок.
 */
export interface SemanticTrap {
  /** Ошибочное слово (основа; аффиксы справа учитываются автоматически). */
  wrong: string;
  /** Что имелось в виду. */
  right: string;
  /** Маркеры контекста (основы слов) в окне ±5 слов вокруг ошибочного. */
  markers: readonly string[];
  /** Считать «цифра-дефис» перед словом маркером («11-сынық» → «11-сынып»). */
  digitHyphen?: boolean;
}

