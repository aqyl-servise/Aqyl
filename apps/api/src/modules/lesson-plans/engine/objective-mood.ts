/**
 * Проверка наклонения целей урока — пост-контроль генерации (ТЗ 1.1, дефект 1).
 *
 * Модель охотно возвращает цель командой: «…белсенділігін анықта», «…процесін
 * сипатта». Для КСП это неверно: цель описывает, что ученик ДЕЛАЕТ, а не что
 * ему приказывают. Промпт это запрещает, но запрет в промпте — не гарантия,
 * поэтому результат проверяется кодом.
 *
 * Проверка сделана ТОЛЬКО для казахского и намеренно построена как «белый
 * список», а не как поиск повелительных форм. Казахское повелительное 2-го
 * лица — это голая основа глагола (анықта, сипатта, жаса, салыстыр), у неё нет
 * общего окончания, по которому её можно поймать. Зато у 3-го лица
 * настояще-будущего времени окончание строго одно из четырёх: -ады/-еді (после
 * согласной) и -йды/-йді (после гласной). Казахский — язык с порядком SOV,
 * сказуемое стоит последним, поэтому достаточно посмотреть на последнее слово.
 *
 * Для русского и английского такая проверка не работает: там глагол не обязан
 * быть последним словом («определяет активность металлов»), и белый список
 * окончаний давал бы ложные срабатывания. Эти языки контролирует промпт.
 */

/** Окончания 3-го лица настояще-будущего времени в казахском. */
const KZ_THIRD_PERSON = /(ады|еді|йды|йді)$/;

/** Последнее слово без пунктуации, в нижнем регистре. */
function lastWord(text: string): string {
  const cleaned = (text ?? '')
    .replace(/[.,;:!?)\]»"'\s]+$/u, '')
    .trim()
    .toLowerCase();
  const parts = cleaned.split(/\s+/);
  return parts[parts.length - 1] ?? '';
}

/**
 * Похожа ли цель на форму действия (3-е лицо), а не на команду.
 * Пустая строка считается корректной: её отсеивает вызывающий код.
 */
export function isActionForm(objective: string, language?: string): boolean {
  if ((language ?? 'kz') !== 'kz') return true;
  const w = lastWord(objective);
  if (!w) return true;
  return KZ_THIRD_PERSON.test(w);
}

/** Цели, похожие на повелительное наклонение. Пустой массив — всё в порядке. */
export function findImperativeObjectives(objectives: string[], language?: string): string[] {
  return (objectives ?? []).filter((o) => o && !isActionForm(o, language));
}
